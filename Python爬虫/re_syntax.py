#----------------------------------------正则表达式语法-----------------------------------------
import re

s1 = "18809090000是我的手机号，188开头的，以00结尾的；我的另一个手机号是15500008888，两个QQ号分别是1259989092和13809091293821，邮箱为python666@163.com，请给我发邮件。"
s3 = "18809090000"
# 正则表达式
# . 匹配任意一个字符(除\n)
print(re.findall(r"188.*", s1)) # * 匹配任何个(0次或无数次) --> s1 的全部字符串
print(re.findall(r"188.?", s1)) # ? 匹配0个或者1个 (最多出现一次) --> ['1880', '188开']
print(re.findall(r"188.+", s1)) # + 匹配1个或者多个 (最少出现一次) --> s1 的全部字符串

# \d 匹配任意一个数字
# \D 匹配任意一个非数字
print(re.findall(r"188\d{8}", s1)) # {8} 匹配8个 --> ['18809090000']
print(re.findall(r"155\d{6,10}", s1)) # {6,10} 匹配6到10个 --> ['15500008888']
print(re.findall(r"155\d{6,}", s1)) # {6,} 匹配6个或者更多 --> ['15500008888']

# | 或的意思，匹配[]中的任意一个表达式
print(re.findall(r"1[3|8]\d{8}", s1)) # [3|8] 匹配 3 或者 8 --> ['1880909000', '1380909129']
print(re.findall(r"1[38]\d{8}", s1)) # [38] 匹配 3 或者 8 --> ['1880909000', '1380909129']
print(re.findall(r"1[^38]\d{8}", s1)) # [^38] 匹配非 3或者8 --> ['1550000888', '1259989092']
print(re.findall(r"1[3-9]\d{8}", s1)) # [3-9] 匹配 3 到 9 (范围) --> ['1880909000', '1550000888', '1380909129']
print(re.findall(r"^1[3-9]\d{9}", s1)) # ^ 匹配开头 --> ['18809090000']
print(re.findall(r"^1[3-9]\d{9}$", s1)) # $ 匹配结尾 --> [], 因为 s1 后面还有字符串, 匹配不到
print(re.findall(r"^1[3-9]\d{9}$", s3)) # $ 匹配结尾 --> ['18809090000']

# \w 匹配任何单词字符 (a-z、A-Z、0-9、_、其它语言字符) -- 默认行为
# \W 匹配任何非单词字符, 与 \w 相对
# \. 表示匹配点字符
print(re.findall(r"\w+@\w+\.\w+", s1)) # --> ['邮箱为python666@163.com']
# re.ASCII, 使 \w 匹配 ASCII 中的字符，即匹配 (a-z、A-Z、0-9、_)
print(re.findall(r"\w+@\w+\.\w+", s1, re.ASCII)) # --> ['python666@163.com']

# 注意
# () 将括号中的字符作为一个分组
s2 = "现在的时间是2026-02-06 10:05:25, 今天的天气还可以, 气温是28度 "
print(re.findall(r"\d{4}-\d{2}-\d{2}", s2)) # --> ['2026-02-06']
print(re.findall(r"(\d{4})-(\d{2})-(\d{2})", s2)) # --> [('2026', '02', '06')]